"""ACL-checked image serving (Phase 4): gateway-proxied MinIO, never presigned.

The frontend renders citation thumbnails (figure crops, page renders) through
these endpoints. Rule 5 applies to image bytes exactly as to chunks: a valid
JWT is required, and the document's collection must be in the caller's ACL
scope — otherwise 404 (never 403; existence must not leak). MinIO itself stays
internal-network-only; no presigned or public URLs exist anywhere.
"""

from __future__ import annotations

import asyncio
import re
import uuid

from fastapi import APIRouter, Depends, HTTPException, Response, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.config import get_settings
from app.core.deps import get_current_user
from app.core.rbac import can_access_collection
from app.db.session import get_db
from app.ingestion.object_store import (
    figure_key,
    get_object_store,
    page_key,
    to_uri,
)
from app.models.document import Document
from app.models.user import User

router = APIRouter(prefix="/media", tags=["media"])
_settings = get_settings()

# Figure ids are generated by the ingestion pipeline; anything else is a probe.
_FIGURE_ID = re.compile(r"^[A-Za-z0-9_-]{1,128}$")


async def _authorized_document(
    document_id: uuid.UUID, user: User, db: AsyncSession
) -> Document:
    doc = await db.get(Document, document_id)
    if doc is None or not await can_access_collection(db, user, doc.collection_id):
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Not found")
    return doc


async def _png_response(uri: str) -> Response:
    store = get_object_store()
    try:
        png = await asyncio.to_thread(store.get, uri)
    except Exception as exc:  # noqa: BLE001 - missing/unreadable object
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Not found") from exc
    # Authorization is per-request; never let a shared cache serve this.
    return Response(content=png, media_type="image/png",
                    headers={"Cache-Control": "private, max-age=300"})


@router.get("/pages/{document_id}/{page_no}")
async def page_image(
    document_id: uuid.UUID,
    page_no: int,
    user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> Response:
    await _authorized_document(document_id, user, db)
    if page_no < 1:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Not found")
    return await _png_response(
        to_uri(_settings.minio_bucket_pages, page_key(document_id, page_no)))


@router.get("/figures/{document_id}/{figure_id}")
async def figure_image(
    document_id: uuid.UUID,
    figure_id: str,
    user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> Response:
    await _authorized_document(document_id, user, db)
    if not _FIGURE_ID.match(figure_id):
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Not found")
    return await _png_response(
        to_uri(_settings.minio_bucket_figures, figure_key(document_id, figure_id)))
